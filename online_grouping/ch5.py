"""Chapter 5: deterministic sliding-window task grouping.

This module implements the sequential framework of
Section 5.4 of the thesis exactly as stated there:

* the constant-rate pressure model of eq. (5.3),
* the safe deadline of eq. (5.6),
* the admissible day set of eq. (5.7) and its window restriction (5.9),
* Model 1 (cluster-count minimisation, eq. (5.23)) solved inside a window
  with the shared constraints (5.15)-(5.21),
* one task per compartment per window (eq. (5.30)),
* translation of the successors' reference dates after each fix (5.32),
* the adaptive window advancement rule (5.33).

It is used to reproduce the illustrative instance of
Section 5.6.1 and to draw ``fig_grouping_result.pdf``; every number
quoted for that instance comes from the JSON/CSV artefacts written here.

Run:  python3 -m online_grouping.ch5 --seed 7 --out results/ch5
"""
from __future__ import annotations

import argparse
import csv
