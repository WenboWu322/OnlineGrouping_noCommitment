KAPPA_KG_PER_BAR = 5.993      # eq. of Ch. 4, V = 1 m3, SF6 near 20 degC


def leaked_mass(inst: Ch5Instance, delta: dict[str, float],
                plan: dict[str, int], form: str = 'proportional') -> float:
    """Cumulative SF6 leakage mass over the horizon for a given plan.

    The ideal-gas conversion of Chapter~4 turns a cumulated pressure drop
    into a mass, ``m = kappa * sum_t (p_{t-1} - p_t)``, with ``kappa`` in
    kg/bar for a one-cubic-metre compartment. Two degradation conventions
    are compared:

    ``linear``
        eq. (5.3): a constant pressure drop per day. Over a fixed horizon the
        cumulated drop does not depend on when the refills happen, so no
        grouping decision can change the leaked mass.
    ``proportional``
        the Chapter~4 form, a constant fraction of the current pressure per
        day, which is the ideal-gas behaviour of a leak with fixed
        conductance. Restoring the pressure earlier then raises the cumulated
        drop, which is where a grouping effect on leakage comes from.
    """
    kappa = KAPPA_KG_PER_BAR
    total = 0.0
    for pmec, d in delta.items():
        days = sorted(tau for tid, tau in plan.items()
                      if tid.split('#')[0] == pmec and tau is not None)
        r = d / inst.p_ref           # proportional rate matched at p_ref
        # back-propagate the state to the start of the horizon from the
        # pressure at which the first refill of this compartment is due
        p = inst.p_ref
        if days:
            for _ in range(1, days[0]):
                p = p + d if form == 'linear' else p / (1.0 - r)
            p = min(p, inst.p_nom)
        drop = 0.0
        idx = 0
        for t in range(1, inst.T + 1):
            leak = d if form == 'linear' else r * p
            if idx < len(days) and days[idx] == t:
                # the compartment still leaks on the day it is refilled
                drop += leak
                p = inst.p_nom
                idx += 1
                continue
            drop += leak
            p = p - d if form == 'linear' else p * (1.0 - r)
        total += kappa * drop
    return total


def summarise(inst: Ch5Instance, tasks, by_id, executed, records,
              extra: dict | None = None) -> dict:
    n = sum(1 for t in tasks if t.ident in executed)
    per_day: dict[int, list[str]] = {}
    for tid, day in executed.items():
        per_day.setdefault(day, []).append(tid)
    shifts = [executed[t.ident] - t.tau_base for t in tasks
              if t.ident in executed]
    return dict(
        seed=inst.seed, T=inst.T, n_pmec=inst.n_pmec,
        n_tasks=n,
        n_dispatches=len(per_day),
        max_cluster=max(len(v) for v in per_day.values()),
        reduction_pct=round(100.0 * (n - len(per_day)) / n, 1),
        setup_before=inst.c_set * n,
        setup_after=inst.c_set * len(per_day),
        n_windows=len(records),
        fallback_windows=sum(1 for r in records if r.fallback),
        advanced=sum(1 for s in shifts if s < 0),
        unchanged=sum(1 for s in shifts if s == 0),
        delayed=sum(1 for s in shifts if s > 0),
        mean_abs_shift=round(float(np.mean([abs(s) for s in shifts])), 2),
        max_abs_shift=int(max(abs(s) for s in shifts)),
        dispatches={str(d): sorted(v) for d, v in sorted(per_day.items())},
        **(extra or {}),
    )


def dump(out: Path, inst, tasks, by_id, executed, records, summary) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / 'ch5_illustrative.json').write_text(json.dumps(
        dict(instance=asdict(inst), summary=summary,
             tasks=[dict(ident=t.ident, pmec=t.pmec, cycle=t.cycle,
                         tau_base=t.tau_base, tau0_at_solve=t.tau0_at_solve,
                         tau0_final=t.tau0,
                         assigned=executed.get(t.ident), window=t.window,
                         shift=(executed[t.ident] - t.tau_base
                                if t.ident in executed else None))
                    for t in tasks],
             windows=[asdict(r) for r in records]), indent=2) + '\n')
    with (out / 'ch5_illustrative_tasks.csv').open('w', newline='') as fh:
        wr = csv.writer(fh)
        wr.writerow(['task', 'pmec', 'cycle', 'tau_base', 'tau0_at_solve',
                     'tau0_final', 'assigned', 'window', 'shift'])
        for t in tasks:
            wr.writerow([t.ident, t.pmec, t.cycle, t.tau_base,
                         t.tau0_at_solve, t.tau0, executed.get(t.ident),
                         t.window,
                         (executed[t.ident] - t.tau_base
                          if t.ident in executed else '')])
    with (out / 'ch5_illustrative_windows.csv').open('w', newline='') as fh:
        wr = csv.writer(fh)
        wr.writerow(['window', 'start', 'end', 'status', 'objective',
                     'fallback', 'n_tasks', 'n_clusters', 'cluster_days'])
        for r in records:
            wr.writerow([r.index, r.start, r.end, r.status, r.objective,
                         r.fallback, len(r.tasks), len(r.clusters),
                         ' '.join(str(d) for d in r.clusters)])


