# figure of the illustrative instance
# ----------------------------------------------------------------------

def figure(inst: Ch5Instance, tasks, executed, records, out: Path) -> None:
    """Two-panel view of the illustrative instance.

    Left: the input maintenance plan. Right: the plan returned by the
    sliding-window grouping, with the dispatch days shaded, the number of
    tasks grouped on each of them, and an arrow for every task that was
    moved. Markers are coloured by the window in which the task was fixed.
    """
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    ids = inst.pmec_ids()
    ypos = {i: len(ids) - k for k, i in enumerate(ids)}
    colours = plt.get_cmap('tab10')

    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.0), sharey=True)

    for ax in axes:
        ax.set_xticks(range(1, inst.T + 1, 2))
        ax.set_xlim(0.2, inst.T + 0.8)
        ax.set_ylim(0.4, len(ids) + 0.8)
        ax.set_yticks(list(ypos.values()), [i.replace('PMEC_', 'C')
                                           for i in ids], fontsize=7)
        ax.set_xlabel('day of the planning horizon', fontsize=8)
        ax.grid(axis='x', color='0.9', linewidth=0.5)
        for i in ids:
            ax.plot([0.4, inst.T + 0.6], [ypos[i]] * 2, color='0.85',
                    linewidth=0.7, zorder=1)

    ax = axes[0]
    ax.set_title(f'input plan: {len(tasks)} GR tasks', fontsize=9)
    for t in tasks:
        ax.plot(t.tau_base, ypos[t.pmec], 'o', color='0.35', markersize=5,
                zorder=3)

    ax = axes[1]
    per_day: dict[int, list] = {}
    for t in tasks:
        if t.ident in executed:
            per_day.setdefault(executed[t.ident], []).append(t)
    for day, group in per_day.items():
        ax.axvspan(day - 0.45, day + 0.45, color='tab:blue', alpha=0.10,
                   zorder=1)
        ax.annotate(f'{len(group)}', (day, len(ids) + 0.6), ha='center',
                    fontsize=7, color='tab:blue')
    for t in tasks:
        if t.ident not in executed:
            continue
        day = executed[t.ident]
        col = colours((t.window or 1) % 10)
        if day != t.tau_base:
            ax.annotate('', xy=(day, ypos[t.pmec]), xytext=(t.tau_base,
                                                            ypos[t.pmec]),
                        arrowprops=dict(arrowstyle='->', color='0.55',
                                        linewidth=0.7, shrinkA=2, shrinkB=2),
                        zorder=2)
            ax.plot(t.tau_base, ypos[t.pmec], 'o', color='none',
                    markeredgecolor='0.6', markersize=5, zorder=3)
        ax.plot(day, ypos[t.pmec], 'o', color=col, markersize=5.5, zorder=4)
    n_win = len({t.window for t in tasks if t.window})
    ax.set_title(f'after grouping: {len(per_day)} dispatch days, '
                 f'{n_win} windows', fontsize=9)

    handles = [plt.Line2D([], [], marker='o', linestyle='', color=colours(w % 10),
                          label=f'fixed in window {w}')
               for w in sorted({t.window for t in tasks if t.window})]
    handles.append(plt.Line2D([], [], marker='o', linestyle='', color='0.35',
                              label='input reference date'))
    handles.append(plt.Line2D([], [], color='0.55', linewidth=0.8,
                              label='date moved'))
    fig.legend(handles=handles, loc='lower center', ncol=4, fontsize=7,
               frameon=False, bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=(0, 0.06, 1, 1))
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, bbox_inches='tight')
    plt.close(fig)



def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--seed', type=int, default=7)
    ap.add_argument('--T', type=int, default=30)
    ap.add_argument('--pmecs', type=int, default=10)
    ap.add_argument('--K', type=int, default=5)
    ap.add_argument('--rate-low', type=float, default=0.012)
    ap.add_argument('--rate-high', type=float, default=0.030)
    ap.add_argument('--out', default='results/ch5')
    ap.add_argument('--figure', default='')
    ap.add_argument('--thesis-figures', default='')
    args = ap.parse_args(argv)

    inst = Ch5Instance(T=args.T, n_pmec=args.pmecs, K_clus=args.K, seed=args.seed,
                       rate_low=args.rate_low, rate_high=args.rate_high)
    p0, delta, tasks, by_id, executed, records, extra = run_ch5(inst)
    summary = summarise(inst, tasks, by_id, executed, records, extra)
    dump(Path(args.out), inst, tasks, by_id, executed, records, summary)
    summary['leaked_mass_linear_input'] = round(
        leaked_mass(inst, delta, {t.ident: t.tau_base for t in tasks},
                    'linear'), 3)
    summary['leaked_mass_linear_grouped'] = round(
        leaked_mass(inst, delta, executed, 'linear'), 3)
    summary['leaked_mass_proportional_input'] = round(
        leaked_mass(inst, delta, {t.ident: t.tau_base for t in tasks},
                    'proportional'), 3)
    summary['leaked_mass_proportional_grouped'] = round(
        leaked_mass(inst, delta, executed, 'proportional'), 3)
    if args.figure:
        figure(inst, tasks, executed, records, Path(args.figure))
        print(f'wrote {args.figure}')
    if args.thesis_figures:
        shutil.copy(Path(args.figure), Path(args.thesis_figures))
        print(f'copied to {args.thesis_figures}')
    dump(Path(args.out), inst, tasks, by_id, executed, records, summary)
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
