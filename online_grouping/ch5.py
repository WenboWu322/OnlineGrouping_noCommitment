from pathlib import Path

import numpy as np

from .grouping import WindowSpec, solve_window
from .config import Config, ScenarioConfig, PolicyConfig


# ----------------------------------------------------------------------
# instance
# ----------------------------------------------------------------------

@dataclass
class Ch5Instance:
    """Input maintenance plan of a deterministic Chapter 5 instance."""
    T: int = 30
    n_pmec: int = 10
    p_nom: float = 3.5
    p_ref: float = 3.2
    p_min: float = 3.0
    delta_adv: int = 3
    delta_safe: int = 2
    K_clus: int = 5
    c_set: float = 10.0
    eta_minus: float = 5.0
    eta_plus: float = 10.0
    rate_low: float = 0.012
    rate_high: float = 0.030
    p0_low: float = 3.21
    p0_high: float = 3.5
    seed: int = 0

    def pmec_ids(self) -> list[str]:
        return [f'PMEC_{k + 1:03d}' for k in range(self.n_pmec)]


@dataclass
class Task:
    ident: str
    pmec: str
    cycle: int
    tau_base: int          # date in the input plan
    tau0: int              # current reference date (updated by the procedure)
    processed: bool = False
    assigned: int | None = None
    window: int | None = None
    tau0_at_solve: int | None = None


def build_plan(inst: Ch5Instance) -> tuple[dict[str, float], dict[str, float],
                                           list[Task]]:
    """Initial pressures, degradation rates and the input maintenance plan.

    The plan is generated by the threshold rule of Chapter 5: starting from
    the initial pressure, the first task date is the first day at which the
    predicted pressure is at or below ``p_ref``; after a refilling the
    pressure is restored to ``p_nom`` and the same rule gives the next task.
    """
    rng = np.random.default_rng(inst.seed)
    ids = inst.pmec_ids()
    p0 = {i: float(rng.uniform(inst.p0_low, inst.p0_high)) for i in ids}
    delta = {i: float(rng.uniform(inst.rate_low, inst.rate_high)) for i in ids}

    tasks: list[Task] = []
    for i in ids:
        cycle = 0
        # first task: the first integer day at which the pressure predicted
        # from the initial state is at or below the refilling threshold
        tau = int(np.ceil((p0[i] - inst.p_ref) / delta[i]))
        # interval between two successive refilled cycles, in integer days
        step = int(np.ceil((inst.p_nom - inst.p_ref) / delta[i]))
        while tau <= inst.T:
            tasks.append(Task(ident=f'{i}#{cycle}', pmec=i, cycle=cycle,
                              tau_base=tau, tau0=tau))
            cycle += 1
            tau += step
    return p0, delta, tasks


def safe_deadline(inst: Ch5Instance, delta: float, s: int, p_at_s: float) -> int:
    """eq. (5.6) with the crossing day excluded.

    ``s`` is the day the state is taken (0 for the first task, otherwise the
    committed execution date of the predecessor), ``p_at_s`` the pressure
    then.  The unmaintained trajectory reaches the floor at
    ``s + (p_at_s - p_min) / delta``; the first integer day at or below the
    floor is the ceiling of that quantity and is not admissible, so the
    latest admissible day is one day earlier, less the safety margin.
    """
    crossing = s + (p_at_s - inst.p_min) / delta
    return int(np.ceil(crossing)) - 1 - inst.delta_safe


# ----------------------------------------------------------------------
# sequential framework
# ----------------------------------------------------------------------

@dataclass
class WindowRecord:
    index: int
    start: int
    end: int
    tasks: list[str] = field(default_factory=list)
    clusters: list[int] = field(default_factory=list)
    status: str = ''
    objective: float | None = None
    fallback: bool = False


def run_ch5(inst: Ch5Instance, solver: str = 'auto'):
    """Sliding-window grouping of Algorithm 5.1 with Model 1."""
    p0, delta, tasks = build_plan(inst)
    by_id = {t.ident: t for t in tasks}
    pending = [t.ident for t in tasks]
    executed: dict[str, int] = {}      # task id -> fixed execution date
    records: list[WindowRecord] = []

    cfg = Config(scenario=ScenarioConfig(T=inst.T, n_pmec=inst.n_pmec,
                                         p_nom=inst.p_nom, p_ref=inst.p_ref,
                                         p_min=inst.p_min,
                                         delta_adv=inst.delta_adv,
                                         delta_safe=inst.delta_safe,
                                         K_clus=inst.K_clus,
                                         c_set=inst.c_set,
                                         eta_minus=inst.eta_minus,
                                         eta_plus=inst.eta_plus),
                 policy=PolicyConfig(solver=solver))

    def predecessor_state(task: Task) -> tuple[int, float]:
        """State (day, pressure) from which the task's own cycle is assessed."""
        if task.cycle == 0:
            return 0, p0[task.pmec]
        prev = executed.get(f'{task.pmec}#{task.cycle - 1}')
        if prev is None:
            # not fixed yet: the input-plan position is the best available
            # information, and the pressure restored there is nominal
            return task.tau_base, inst.p_nom
        return prev, inst.p_nom

    w_start, index = 1, 0
    while w_start <= inst.T and any(not by_id[t].processed for t in pending):
        w_end = min(w_start + 10 - 1, inst.T)
        window = list(range(w_start, w_end + 1))
        index += 1

        cand: dict[str, Task] = {}
        for tid in pending:
            t = by_id[tid]
            if t.processed:
                continue
            if not (w_start <= t.tau0 <= w_end):
                continue
            cur = cand.get(t.pmec)
            if cur is None or t.tau0 < cur.tau0:
                cand[t.pmec] = t
        selected = list(cand.values())

        rec = WindowRecord(index=index, start=w_start, end=w_end)
        if selected:
            domains, tau0 = {}, {}
            for t in selected:
                s, p_s = predecessor_state(t)
                d_safe = safe_deadline(inst, delta[t.pmec], s, p_s)
                lo = t.tau0 - inst.delta_adv
                domains[t.ident] = [d for d in window if lo <= d <= d_safe]
                tau0[t.ident] = t.tau0
            spec = WindowSpec(tasks=[t.ident for t in selected], days=window,
                              domains=domains, tau0=tau0, announced={},
                              lock_until=None, objective='M1')
            res = solve_window(spec, cfg)
            rec.status, rec.objective = res.status, res.objective
            rec.tasks = [t.ident for t in selected]
            rec.clusters = list(res.clusters)
            if res.status in ('optimal', 'time_limit') and res.assignment:
                for t in selected:
                    executed[t.ident] = res.assignment.get(t.ident, t.tau0)
                    t.assigned = executed[t.ident]
            else:
                rec.fallback = True
                for t in selected:
                    executed[t.ident] = t.tau0
                    t.assigned = t.tau0
            for t in selected:
                t.processed, t.window = True, index
                t.tau0_at_solve = tau0[t.ident]
                shift = executed[t.ident] - t.tau0
                # eq. (5.32): translation of the successors of this compartment
                for other in tasks:
                    if other.pmec == t.pmec and not other.processed \
                            and other.cycle > t.cycle:
                        other.tau0 += shift
        records.append(rec)

        # eq. (5.33): adaptive advancement
        remain = [by_id[t].tau0 for t in pending
                  if not by_id[t].processed and w_start <= by_id[t].tau0 <= w_end]
        w_start = min(remain) if remain else w_end + 1

    # Tasks whose reference date was translated out of every window, or out of
    # the horizon, are never revisited by the procedure: they keep their
    # current reference date and are counted separately.
    outside = 0
    for t in tasks:
        if t.processed:
            continue
        if t.tau0 <= inst.T:
            executed[t.ident] = t.tau0
            t.assigned = t.tau0
        else:
            outside += 1
    summary_extra = dict(tasks_not_revisited=sum(
        1 for t in tasks if not t.processed),
        tasks_outside_horizon=outside)
    return p0, delta, tasks, by_id, executed, records, summary_extra


